"""
Scenario Analysis Module

Employee Attrition Analytics

This module evaluates the potential impact
of workload-management interventions on
predicted employee attrition risk.
"""

import pandas as pd

def scenario_a_optimization(df):
    """
    Scenario A:
    Project Load Optimization

    Business hypothesis:
    Reducing excessive project load may lower
    employee attrition risk.

    Intervention:
    6 projects -> 5 projects
    7 projects -> 5 projects
    """

    df = df.copy()
    df.loc[df["number_project"] == 6, "number_project"] = 5
    df.loc[df["number_project"] == 7, "number_project"] = 5
    return df

def scenario_b_optimization(df):
    """
    Scenario B:
    Working Hours Optimization

    Business hypothesis:
    Reducing excessive monthly working hours
    may improve employee retention.

    Intervention:
    220+ monthly hours -> 200 monthly hours
    """

    df = df.copy()
    df.loc[
        df["average_monthly_hours"] > 220,
        "average_monthly_hours"] = 200
    return df

def scenario_c_combined_strategy(df):
    """
    Scenario C:
    Combined Workload Strategy

    Business hypothesis:
    Simultaneously reducing excessive project
    loads and monthly working hours may provide
    the strongest retention impact.
    """

    df = df.copy()
    df.loc[df["number_project"] == 6, "number_project"] = 5
    df.loc[df["number_project"] == 7, "number_project"] = 5
    df.loc[
        df["average_monthly_hours"] > 220,
        "average_monthly_hours"
    ] = 200
    return df