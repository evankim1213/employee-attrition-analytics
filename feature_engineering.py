"""
Feature Engineering Module
Employee Attrition Analytics
"""

import pandas as pd


def create_workload_intensity(df):
    """
    Workload intensity represents average working hours
    allocated per assigned project.

    Business hypothesis:
    Employees experiencing heavier workload per project
    are more likely to experience burnout and attrition.
    """

    df = df.copy()

    df["workload_intensity"] = (
        df["average_monthly_hours"] / df["number_project"]
    )

    return df


def create_tenure_bracket(df):
    """
    Tenure bracket categorizes employees into
    different career lifecycle stages.

    0 = Short Tenure (Tenure <= 2)
    1 = Mid Tenure   (3 <= Tenure <= 6)
    2 = Long Tenure  (Tenure > 6)

    Business hypothesis:
    Employees at different tenure stages may experience
    different levels of career plateau and different
    growth opportunities, which can influence attrition risk.
    """

    df = df.copy()

    df["tenure_bracket"] = pd.cut(
        df["tenure"],
        bins=[0, 3, 6, 100],
        labels=[0, 1, 2]
    )

    return df


def create_overworked_flag(df):
    """
    Overworked flag represents employees
    working more than 270 hours per month.

    Business hypothesis:
    Employees working excessive monthly hours
    may face elevated burnout and attrition risk.

    EDA findings indicated extremely high attrition
    among employees working beyond this threshold.
    """

    df = df.copy()

    df["overworked_flag"] = (
        df["average_monthly_hours"] > 270
    ).astype(int)

    return df


def create_promotion_workload_interaction(df):
    """
    Promotion-workload interaction captures the relationship
    between promotion history and workload.

    Business hypothesis:
    Employees carrying high workloads may respond
    differently to burnout risk depending on whether
    they recently received career advancement opportunities.
    """

    df = df.copy()

    df["promotion_workload_interaction"] = (
        df["promotion_last_5years"]
        * df["average_monthly_hours"]
    )

    return df

